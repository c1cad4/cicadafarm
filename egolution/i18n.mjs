let language = "en";
try {
  language = localStorage.getItem("egolution-language") || "en";
} catch {}
if (!["en", "ru", "zh"].includes(language)) language = "en";
export const lang = () => language;
export const t = (k) => ({ en, ru, zh })[language][k] ?? en[k] ?? k;
export function translate(value = language) {
  language = ["en", "ru", "zh"].includes(value) ? value : "en";
  document.documentElement.lang = language;
  document
    .querySelectorAll("[data-i18n]")
    .forEach((e) => (e.textContent = t(e.dataset.i18n)));
  document.querySelector("#language").value = language;
  document.querySelector("#sound").ariaLabel = t("sound");
  document.querySelector("#pause").ariaLabel = t("pause");
  document.querySelector("#helpOpen").ariaLabel = t("help");
  document
    .querySelectorAll("[data-close]")
    .forEach((e) => (e.ariaLabel = t("close")));
  try {
    localStorage.setItem("egolution-language", language);
  } catch {}
}
